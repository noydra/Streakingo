object I18n {
    val LANGUAGES = linkedMapOf("en" to "English", "tr" to "Türkçe", "zh" to "中文")
    const val DEFAULT = "en"

    var language by mutableStateOf(DEFAULT)
        private set

    fun changeLanguage(lang: String) {
        language = if (lang in STRINGS) lang else DEFAULT
    }
}

fun t(key: String, vararg params: Pair<String, Any?>): String {
    var text = STRINGS[I18n.language]?.get(key) ?: STRINGS[I18n.DEFAULT]?.get(key) ?: key
    for ((name, value) in params) text = text.replace("{$name}", value.toString())
    return text
}

fun courseLanguage(code: String?): String =
    COURSE_LANGUAGES[I18n.language]?.get(code) ?: code.orEmpty()

